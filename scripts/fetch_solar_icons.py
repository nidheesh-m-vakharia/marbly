#!/usr/bin/env python3
"""Download Solar icons (Bold style) from the Iconify API and embed them in
Sources/Marbly/Settings/SolarIcon.swift. Solar is by 480 Design, CC BY 4.0.

    python3 scripts/fetch_solar_icons.py

Add an icon by adding a `swift_case: solar-name` pair to ICONS and re-running.
"""

from pathlib import Path
from urllib.request import Request, urlopen

ICONS = {
    # Settings sidebar
    "palette": "palette-bold",
    "sun": "sun-bold",
    "keyboard": "keyboard-bold",
    "volume": "volume-loud-bold",
    "monitor": "monitor-bold",
    "shield": "shield-keyhole-bold",
    # Status and notes
    "checkCircle": "check-circle-bold",
    "dangerCircle": "danger-circle-bold",
    "dangerTriangle": "danger-triangle-bold",
    "lock": "lock-keyhole-bold",
    "code": "code-square-bold",
    # Menu bar menu
    "volumeCross": "volume-cross-bold",
    "eye": "eye-bold",
    "eyeClosed": "eye-closed-bold",
    "refresh": "refresh-bold",
    "settings": "settings-bold",
    "logout": "logout-3-bold",
}

OUT = Path(__file__).resolve().parent.parent / "Sources/Marbly/Settings/SolarIcon.swift"


def fetch(name: str) -> str:
    # Iconify rejects urllib's default user agent.
    req = Request(f"https://api.iconify.design/solar/{name}.svg", headers={"User-Agent": "marbly-icon-fetch"})
    with urlopen(req) as r:
        svg = r.read().decode().strip()
    # A real size lets NSImage rasterise crisply; SwiftUI and menus scale it anyway.
    return svg.replace('width="1em" height="1em"', 'width="24" height="24"')


def main() -> None:
    svgs = {case: fetch(name) for case, name in ICONS.items()}
    cases = "".join(f"    case {c}\n" for c in ICONS)
    names = "".join(f'        case .{c}: "{n}"\n' for c, n in ICONS.items())
    bodies = "".join(f'        case .{c}: #"{s}"#\n' for c, s in svgs.items())
    OUT.write_text(f'''import AppKit
import SwiftUI

// Generated by scripts/fetch_solar_icons.py. Edit ICONS there and re-run.

/// Solar icons, Bold (solid) style, by 480 Design — CC BY 4.0.
/// https://www.figma.com/community/file/1166831539721848736
/// Embedded so there's nothing to load from disk.
enum SolarIcon: String, CaseIterable {{
{cases}
    /// The icon's name in the Solar set.
    var solarName: String {{
        switch self {{
{names}        }}
    }}

    private var svg: String {{
        switch self {{
{bodies}        }}
    }}

    /// Template image, so it takes the surrounding foreground colour.
    @MainActor var image: NSImage {{
        if let cached = Self.cache[self] {{ return cached }}
        let image = NSImage(data: Data(svg.utf8)) ?? NSImage()
        image.isTemplate = true
        Self.cache[self] = image
        return image
    }}

    /// Sized for a menu item.
    @MainActor func menuImage(size: CGFloat = 16) -> NSImage {{
        let copy = image.copy() as! NSImage
        copy.size = NSSize(width: size, height: size)
        copy.isTemplate = true
        return copy
    }}

    @MainActor private static var cache: [SolarIcon: NSImage] = [:]
}}

/// A Solar icon at a given size, tinted by `foregroundStyle`.
struct Solar: View {{
    let icon: SolarIcon
    var size: CGFloat = 20

    init(_ icon: SolarIcon, size: CGFloat = 20) {{
        self.icon = icon
        self.size = size
    }}

    var body: some View {{
        Image(nsImage: icon.image)
            .renderingMode(.template)
            .resizable()
            .interpolation(.high)
            .frame(width: size, height: size)
            .accessibilityHidden(true)
    }}
}}
''')
    print(f"Wrote {len(ICONS)} icons to {OUT.relative_to(OUT.parents[3])}")


if __name__ == "__main__":
    main()
